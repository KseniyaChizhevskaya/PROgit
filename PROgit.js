/*GIT

Основные понятия Git

Термин	Что это
**Репозиторий (repo)**	Папка с проектом + история изменений
**Commit**	"Снимок" изменений в коде с комментарием
**Branch (ветка)**	Независимая линия разработки
**Remote**	Удалённый репозиторий (например, на GitHub)
**Push**	Отправка изменений на GitHub
**Pull / Fetch**	Получение изменений с GitHub
**Clone**	Скачивание всего репозитория с GitHub

Работа с GitHub: пошагово

Создайте репозиторий на GitHub
1. Зайдите на [github.com](https://github.com/)
2. Нажмите **«+» → New repository**
3. Введите имя (например, `my-project`)
4. Выберите **Public** или **Private**
5. НЕ ставьте галочку "Add README" (если вы начинаете локально)
6. Нажмите **Create repository**

Команды Git
1. `git clone`
Что делает:
Команда `git clone` скачивает весь репозиторий с удалённого сервера (например, с GitHub) на ваш компьютер. Это ваш первый шаг, если вы хотите работать над чужим проектом или продолжить работу над своим на новом устройстве.
Как использовать:
Откройте терминал и введите:
git clone https://github.com/username/project-name.git
Что произойдёт:  
Git создаст папку с названием репозитория (`project-name`) и загрузит туда все файлы, историю коммитов и ветки.
Важно:
- Эту команду используют один раз при начале работы с проектом.  
- После клонирования вы уже находитесь в главной ветке (обычно `main` или `master`).

2. `git add`
Что делает: 
Команда `git add` "готовит" изменения к сохранению. Она добавляет изменения из ваших файлов в так называемый "индекс" (staging area) — промежуточную зону перед фиксацией коммита.
Как использовать:  
Если вы изменили файлы, например `index.html` и `script.js`, вы можете добавить их так:
git add index.html script.js
Или добавить все изменения сразу:
git add .
Что произойдёт:**  
Git запомнит текущее состояние указанных файлов как "готовые к коммиту". Теперь они в staging area.
Важно: 
- Без `git add` вы не сможете сделать коммит этих изменений.  
- Вы можете добавить только часть изменений (например, только один файл из десяти), чтобы разделить логику коммитов.

3. `git commit`
Что делает:
Команда `git commit` фиксирует изменения из staging area как новую версию проекта — "снимок" кода с комментарием. Это как сохранение прогресса в игре.
Как использовать:
После `git add` выполните:
git commit -m "Исправил ошибку в кнопке отправки"
Флаг `-m` позволяет сразу написать сообщение (message) к коммиту.
Что произойдёт:
Git создаст новый коммит с уникальным хешем (например, `a1b2c3d...`), запишет ваше имя, email и сообщение, и сохранит текущее состояние файлов.
Важно:
- Сообщение коммита должно быть чётким и описательным.  
- Коммит сохраняется только локально — он ещё не на GitHub! Чтобы отправить — нужен `git push`.

### 4. `git branch`
Что делает: 
Команда `git branch` показывает, создаёт или удаляет ветки. Ветка — это независимая линия разработки. Например, вы можете работать над новой функцией в отдельной ветке, не ломая основной код.
Как использовать:  
- Посмотреть все ветки:
  git branch
  Текущая ветка будет выделена звёздочкой `*`.
- Создать новую ветку (например, для новой функции):
  git branch feature/dark-mode
- Удалить ветку (после того как вы её смёрджили):
  git branch -d feature/dark-mode
Важно: 
- Создание ветки не переключает вас на неё — вы остаётесь в текущей.  
- Для переключения нужна команда `git checkout` (или `git switch` в новых версиях Git).

5. `git checkout`
Что делает: 
Команда `git checkout` переключает вас между ветками или восстанавливает файлы до предыдущего состояния.
Как использовать (переключение веток):
git checkout feature/dark-mode
Теперь вы работаете в ветке `feature/dark-mode`.
Создать и переключиться сразу: 
git checkout -b feature/new-login
Это эквивалентно: сначала `git branch`, потом `git checkout`.
Восстановить файл:
Если вы случайно испортили `style.css` и ещё не делали `git add`, можно вернуть его:
git checkout HEAD -- style.css
Важно: 
- В новых версиях Git (2.23+) рекомендуют использовать `git switch` вместо `checkout` для переключения веток, и `git restore` — для восстановления файлов. Но `checkout` всё ещё работает и широко используется.

6. `git push`
Что делает: 
Команда `git push` отправляет ваши коммиты из локального репозитория на удалённый сервер (например, GitHub). Без этого ваши изменения останутся только у вас на компьютере.
Как использовать: 
В первый раз (когда вы создаёте новую ветку):
git push -u origin feature/dark-mode
Флаг `-u` связывает вашу локальную ветку с удалённой — в будущем можно будет просто писать `git push`.
После этого:
git push
Что произойдёт:
Ваши коммиты появятся на GitHub. Теперь коллеги могут их увидеть, или вы можете создать Pull Request.
Важно:  
- Если кто-то уже запушил изменения в ту же ветку, Git может отказать в пуше — сначала нужно сделать `git pull`.

7. `git rebase`
Что делает: 
Команда `git rebase` перемещает (или "переставляет") коммиты одной ветки поверх другой. Это помогает сделать историю коммитов линейной и чистой, без лишних "слияний".
Как использовать:
Допустим, вы работали в ветке `feature`, а в `main` за это время появились новые коммиты. Чтобы "обновить" свою ветку:
git checkout feature
git rebase main
Git возьмёт ваши коммиты и "переложит" их поверх последнего коммита main.
Когда использовать:  
- Перед созданием Pull Request — чтобы ваш код был актуальным.  
- Когда вы хотите избежать "мёрджа" и сохранить чистую историю.
Важно: 
- Никогда не делайте rebase коммитов, которые уже были отправлены на GitHub и видны другим! Это ломает историю для команды.  
- Rebase перезаписывает историю — будьте осторожны.

8. `git revert`
Что делает:
Команда `git revert` отменяет конкретный коммит, создавая новый коммит с противоположными изменениями. Это безопасный способ "отката" без перезаписи истории.
Как использовать:
Сначала найдите хеш коммита, который хотите отменить:
git log --oneline
Затем:
git revert a1b2c3d
Git создаст новый коммит, который отменяет всё, что было сделано в `a1b2c3d`.
Почему это лучше `reset`: 
- `revert` не удаляет старые коммиты — история остаётся целой.  
- Это безопасно для публичных веток (например, `main`), где работают другие.
Когда использовать: 
- Когда вы случайно сломали что-то в продакшене и нужно срочно откатить.  
- В общих ветках, где нельзя переписывать историю.

Заключение

Эти 8 команд — основа повседневной работы с Git:
- `clone` — начать работу с проектом  
- `add` + `commit` — сохранить изменения  
- `branch` + `checkout` — работать параллельно  
- `push` — поделиться с командой  
- `rebase` — сделать историю чище (осторожно!)  
- `revert` — безопасно отменить ошибку*/
